// Command gate is the cooldown gate for curation changes (ADR-0037,
// ADR-0051): for each open pull request labelled curation, it works out what
// the change adds and whether Automap's CI verified it, then merges it,
// labels it needs-human, or leaves it to wait, saying why.
//
//	gate -repo zach/automap -map map
package main

import (
	"encoding/base64"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/zach/automap/ci/internal/gh"
)

func main() {
	repo := flag.String("repo", "zach/automap", "the repository")
	mapDir := flag.String("map", "map", "the map on main, for its contracts' major versions")
	flag.Parse()

	var pulls []struct {
		Number int `json:"number"`
		Labels []struct {
			Name string `json:"name"`
		} `json:"labels"`
		Head struct {
			SHA string `json:"sha"`
			Ref string `json:"ref"`
		} `json:"head"`
	}
	if err := gh.Get("/repos/"+*repo+"/pulls?state=open&per_page=100", &pulls); err != nil {
		fail(err)
	}
	majors := contractMajors(*mapDir)
	for _, p := range pulls {
		var labels []string
		for _, l := range p.Labels {
			labels = append(labels, l.Name)
		}
		if !slices.Contains(labels, "curation") || slices.Contains(labels, "needs-human") {
			continue
		}
		change, err := describe(*repo, p.Number, p.Head.SHA)
		if err != nil {
			fmt.Printf("#%d: %v\n", p.Number, err)
			continue
		}
		change.Majors = majors
		action, why := Decide(change, time.Now())
		fmt.Printf("#%d (%s): %s: %s\n", p.Number, p.Head.Ref, action, why)
		switch action {
		case "merge":
			if err := gh.Do("PUT", fmt.Sprintf("/repos/%s/pulls/%d/merge", *repo, p.Number), map[string]string{"merge_method": "merge", "sha": p.Head.SHA}, nil); err != nil {
				fmt.Printf("#%d: merging: %v\n", p.Number, err)
				continue
			}
			// A merge by the workflow's token starts no workflows: start the
			// verification that publishes the new version's evidence.
			gh.Do("POST", "/repos/"+*repo+"/actions/workflows/verify-map.yml/dispatches", map[string]string{"ref": "main"}, nil)
		case "human":
			gh.Do("POST", fmt.Sprintf("/repos/%s/issues/%d/labels", *repo, p.Number), map[string][]string{"labels": {"needs-human"}}, nil)
			gh.Do("POST", fmt.Sprintf("/repos/%s/issues/%d/comments", *repo, p.Number), map[string]string{"body": "This change waits for the product owner: " + why + " (ADR-0069).\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}, nil)
		}
	}
}

// describe gathers what the gate decides on for one pull request: the
// files it adds, the library versions it adds with their release dates,
// and whether CI and Verify map passed on its head.
func describe(repo string, number int, sha string) (Change, error) {
	var c Change
	var files []struct {
		Name   string `json:"filename"`
		Status string `json:"status"`
	}
	if err := gh.Get(fmt.Sprintf("/repos/%s/pulls/%d/files?per_page=100", repo, number), &files); err != nil {
		return c, err
	}
	for _, f := range files {
		if f.Status == "added" {
			c.Added = append(c.Added, f.Name)
		}
		if strings.HasPrefix(f.Name, "map/libraries/") && f.Status == "modified" {
			added, err := addedVersions(repo, f.Name, sha)
			if err != nil {
				return c, err
			}
			c.Versions = append(c.Versions, added...)
		}
	}
	var runs struct {
		Runs []struct {
			Name       string `json:"name"`
			Status     string `json:"status"`
			Conclusion string `json:"conclusion"`
		} `json:"workflow_runs"`
	}
	if err := gh.Get("/repos/"+repo+"/actions/runs?head_sha="+sha+"&per_page=50", &runs); err != nil {
		return c, err
	}
	// The newest run of each workflow decides.
	seen := map[string]bool{}
	for _, r := range runs.Runs {
		if seen[r.Name] {
			continue
		}
		seen[r.Name] = true
		ok := r.Status == "completed" && r.Conclusion == "success"
		switch r.Name {
		case "CI":
			c.ChecksOK = ok
		case "Verify map":
			c.EvidenceOK = ok
		}
	}
	return c, nil
}

// addedVersions lists the versions a library entry has at sha that it
// doesn't have on main.
func addedVersions(repo, file, sha string) ([]Version, error) {
	read := func(ref string) ([]Version, error) {
		var content struct {
			Content string `json:"content"`
		}
		if err := gh.Get("/repos/"+repo+"/contents/"+file+"?ref="+ref, &content); err != nil {
			return nil, err
		}
		raw, err := base64.StdEncoding.DecodeString(strings.ReplaceAll(content.Content, "\n", ""))
		if err != nil {
			return nil, err
		}
		var lib struct {
			ID       string    `json:"id"`
			Versions []Version `json:"versions"`
		}
		if err := json.Unmarshal(raw, &lib); err != nil {
			return nil, err
		}
		for i := range lib.Versions {
			lib.Versions[i].Library = lib.ID
		}
		return lib.Versions, nil
	}
	head, err := read(sha)
	if err != nil {
		return nil, err
	}
	base, err := read("main")
	if err != nil {
		return nil, err
	}
	var out []Version
	for _, v := range head {
		if !slices.ContainsFunc(base, func(b Version) bool { return b.Version == v.Version }) {
			out = append(out, v)
		}
	}
	return out, nil
}

var majorFile = regexp.MustCompile(`^(\d+)\.\d+\.\d+\.json$`)

// contractMajors is each contract's highest major version on main.
func contractMajors(mapDir string) map[string]int {
	out := map[string]int{}
	dirs, _ := os.ReadDir(filepath.Join(mapDir, "contracts"))
	for _, d := range dirs {
		files, _ := os.ReadDir(filepath.Join(mapDir, "contracts", d.Name()))
		for _, f := range files {
			if m := majorFile.FindStringSubmatch(f.Name()); m != nil {
				if major, _ := strconv.Atoi(m[1]); major > out[d.Name()] {
					out[d.Name()] = major
				}
			}
		}
	}
	return out
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gate:", err)
	os.Exit(1)
}
