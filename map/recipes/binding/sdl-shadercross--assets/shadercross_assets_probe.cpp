// assets.reads-through-interface: cooking a SPIR-V file reads it once,
// through the assets interface. assets.output-identical: cooking it twice
// gives the same MSL, which SPIRV-Cross produces on every platform.
void am_probe_shadercross_assets(am::Context&) {
    auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
    std::filesystem::path path = std::filesystem::temp_directory_path() / ("automap-probe-" + std::to_string(stamp) + ".spv");
    if (std::FILE* f = std::fopen(path.string().c_str(), "wb")) {
        std::fwrite(tint_spirv, 1, sizeof tint_spirv, f);
        std::fclose(f);
    }
    auto before = am::assets::read_count("sdl-shadercross");
    std::vector<std::uint8_t> first, second;
    bool cooked = am_shadercross_cook(path.string().c_str(), SDL_GPU_SHADERFORMAT_MSL, SDL_SHADERCROSS_SHADERSTAGE_FRAGMENT, "main", first);
    bool through = cooked && am::assets::read_count("sdl-shadercross") == before + 1;
    cooked = am_shadercross_cook(path.string().c_str(), SDL_GPU_SHADERFORMAT_MSL, SDL_SHADERCROSS_SHADERSTAGE_FRAGMENT, "main", second) && cooked;
    std::error_code ignored;
    std::filesystem::remove(path, ignored);
    am::probe::check("assets.reads-through-interface", "sdl-shadercross", through, "ASSET_READ_BYPASSED(sdl-shadercross)");
    am::probe::check("assets.output-identical", "sdl-shadercross", cooked && !first.empty() && first == second,
                     "ASSET_OUTPUT_DIFFERS(sdl-shadercross)");
}
const am::probe::Registration registration("sdl-shadercross--assets", &am_probe_shadercross_assets);

