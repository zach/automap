// The formats SDL_GPU's backends take (SDL_CreateGPUShader).
bool accepted(const char* driver, SDL_GPUShaderFormat format) {
    if (SDL_strcmp(driver, "vulkan") == 0) return format == SDL_GPU_SHADERFORMAT_SPIRV;
    if (SDL_strcmp(driver, "direct3d12") == 0) return format == SDL_GPU_SHADERFORMAT_DXBC || format == SDL_GPU_SHADERFORMAT_DXIL;
    if (SDL_strcmp(driver, "metal") == 0) return format == SDL_GPU_SHADERFORMAT_MSL || format == SDL_GPU_SHADERFORMAT_METALLIB;
    return false;
}

// sdl-shadercross--sdl3.formats-match-backend: glue compiles to a format
// each backend of the composition's platforms takes, and the test shader
// compiled for this platform's device is created on it.
// sdl-shadercross--sdl3.reflection-matches: the shader was created with
// the resource counts reflection reads from it.
void am_probe_shadercross_sdl3(am::Context& ctx) {
    bool formats = true;
    for (const char* driver : {"vulkan", "direct3d12", "metal"}) {
        formats = formats && accepted(driver, am_shadercross_format_for(driver));
    }
    SDL_GPUShaderCreateInfo used = {};
    SDL_GPUShader* shader = am_shadercross_create_shader(ctx.sdl3.gpu_device, tint_spirv, sizeof tint_spirv, "main",
                                                         SDL_SHADERCROSS_SHADERSTAGE_FRAGMENT, &used);
    formats = formats && shader != nullptr && (SDL_GetGPUShaderFormats(ctx.sdl3.gpu_device) & used.format) != 0;
    if (shader != nullptr) SDL_ReleaseGPUShader(ctx.sdl3.gpu_device, shader);
    am::probe::check("sdl-shadercross--sdl3.formats-match-backend", "", formats, "SHADER_FORMAT_REJECTED(sdl-shadercross--sdl3)");

    SDL_ShaderCross_GraphicsShaderMetadata* reflected = SDL_ShaderCross_ReflectGraphicsSPIRV(tint_spirv, sizeof tint_spirv, 0);
    bool counts = reflected != nullptr && reflected->resource_info.num_samplers == 1 && reflected->resource_info.num_uniform_buffers == 1 &&
                  used.num_samplers == reflected->resource_info.num_samplers &&
                  used.num_storage_textures == reflected->resource_info.num_storage_textures &&
                  used.num_storage_buffers == reflected->resource_info.num_storage_buffers &&
                  used.num_uniform_buffers == reflected->resource_info.num_uniform_buffers;
    SDL_free(reflected);
    am::probe::check("sdl-shadercross--sdl3.reflection-matches", "", counts, "RESOURCE_COUNTS_HARDCODED(sdl-shadercross--sdl3)");
}
const am::probe::Registration registration("sdl-shadercross--sdl3", &am_probe_shadercross_sdl3);

